/**
 * Copies Battle Drones into the Skillprint portal (skillprint/fe-refactor) as
 * public/games/live/Battle Drones/:
 *
 *   static/                       the portal build (npm run build:portal: no service worker)
 *   static/iframeTest.html        skillprint-harness.html, the portal's side for testing
 *   cover.jpg                     the key art, for the tile and the backend thumbnail
 *   backend/game-scoring-config.json
 *                                 the parameter manifest the portal sends at session start
 *                                 (sdk_game_parameters), and the GameScoringConfig payload
 *                                 (parameter_definitions, adjustment instructions) for
 *                                 PATCH /scoring/api/games/battle-drones/scoring-config/
 *   README.md                     where it came from and how to rebuild it
 *
 * The knobs come from src/skillprint/params.ts and the instructions from
 * src/skillprint/guidance.ts, so the portal and the game can't drift.
 * Registering the game in the portal's code (localGames.ts, gameConfig.ts,
 * GameAdjustmentTester.tsx) is a one-off, done by hand.
 *
 * Usage: npm run skillprint:portal [-- ../fe-refactor]
 */
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PARAMETERS } from "../src/skillprint/params";
import { ADJUSTMENT_INSTRUCTIONS, SKILL_ADJUSTMENT_INSTRUCTIONS } from "../src/skillprint/guidance";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const portal = resolve(root, process.argv[2] ?? "../fe-refactor");
if (!existsSync(join(portal, "lib/localGames.ts"))) throw new Error(`${portal} isn't the portal (skillprint/fe-refactor)`);
const SLUG = "battle-drones";
const dest = join(portal, "public/games/live/Battle Drones");
const git = (...args: string[]) => execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
const commit = git("rev-parse", "HEAD");
const dirty = git("status", "--porcelain", "--", "src", "index.html", "public", "vite.config.ts", "skillprint-harness.html") !== "";

execFileSync("npm", ["run", "build:portal"], { cwd: root, stdio: "inherit" });

rmSync(join(dest, "static"), { recursive: true, force: true });
mkdirSync(join(dest, "backend"), { recursive: true });
cpSync(join(root, "dist-portal"), join(dest, "static"), { recursive: true });
cpSync(join(root, "skillprint-harness.html"), join(dest, "static/iframeTest.html"));
// the key art, at tile size (macOS sips; elsewhere convert it by hand)
execFileSync("sips", ["-s", "format", "jpeg", "-s", "formatOptions", "82", "-Z", "1024", join(root, "public/assets/ui/keyart-landscape.webp"), "--out", join(dest, "cover.jpg")], { stdio: "ignore" });

const BACKEND_TYPE = { Float: "number", Integer: "integer", Boolean: "boolean" } as const;
const config = {
  game_slug: SLUG,
  is_enabled: true,
  parameter_definitions: Object.fromEntries(
    PARAMETERS.map((p) => [
      p.parameterName,
      { type: BACKEND_TYPE[p.type], min: p.min, max: p.max, default: p.default, description: p.description, adjustment_guide: p.howSdkChangesIt }
    ])
  ),
  adjustment_instructions: ADJUSTMENT_INSTRUCTIONS,
  skill_adjustment_instructions: SKILL_ADJUSTMENT_INSTRUCTIONS,
  notes:
    "Generated by battledrones' tools/skillprint-portal.ts from src/skillprint/params.ts (the names the game's ADJUST_GAME handler takes) and src/skillprint/guidance.ts. Keys 1-9 in GameAdjustmentTester and static/iframeTest.html send the presets in GAME_PARAMETERS.MD.",
  sdk_game_parameters: PARAMETERS.map((p) => ({
    name: p.parameterName,
    type: p.type,
    description: p.description,
    adjustment_guide: p.howSdkChangesIt,
    min_value: String(p.min),
    max_value: String(p.max)
  }))
};
writeFileSync(join(dest, "backend/game-scoring-config.json"), `${JSON.stringify(config, null, 2)}\n`);

writeFileSync(
  join(dest, "README.md"),
  `# Battle Drones

A mobile real-time strategy game: two armies of flying and ground drones
battle for territory and resources. By Simon Willison and Claude
([simonw/battledrones](https://github.com/simonw/battledrones), Apache-2.0).

**Don't edit these files here.** They're built from
[kachergis/battledrones](https://github.com/kachergis/battledrones) at
\`${commit}\`${dirty ? " (with uncommitted changes)" : ""}. Its \`src/skillprint/\`
has the Skillprint link. To update the copy, run this from that checkout, with
fe-refactor beside it:

\`\`\`bash
npm run skillprint:portal
\`\`\`

## How it talks to the portal

The portal owns the session. The game posts \`postMessage\`s to it only when
it is embedded in a page, and only for a match the player plays against the
AI (skirmish, Last Stand, ops, the Daily Op). Duels, online free-for-alls,
AI-vs-AI and replays post nothing.

- \`gameEvent\`: GAME_START (map, mode, difficulty, opener, mutators),
  GAME_END (outcome, kills, losses, score), GAME_PAUSE / GAME_RESUME, and its
  own events: ORDER, UNIT_PRODUCED, BUILDING_COMPLETE, ENEMY_KILLED,
  UNIT_LOST, BUILDING_LOST, UNIT_PROMOTED, CALLDOWN, ENEMY_CALLDOWN,
  UPLINK_CAPTURED, UPLINK_LOST, CRATE_CLAIMED, WAVE_CLEARED, SIDE_ELIMINATED.
- \`gameState\` every 5 s of battle: scrap, income, both armies' value,
  units, buildings, Uplinks held, kills, losses, orders per minute and game
  speed; at the end, \`isGameOver\`, \`outcome\` and \`score\` (the career XP
  the match earned).
- \`screenshot\` every 2 s: the 3D view and its health bars, with the HUD's
  numbers stamped top left.
- \`GAME_COMPLETE\` from the end screen's **📊 Finish** button.

It takes \`ADJUST_GAME\` (the knobs in \`backend/game-scoring-config.json\`),
\`GAME_PAUSE\` and \`GAME_RESUME\`, and forwards keys 1-9 to the adjustment
tester (1-3 also select squads in the game). Knobs set mid-match go into the
battle record, so "Copy replay JSON" still replays the match exactly.

\`static/iframeTest.html\` plays the portal's part for testing: open it from
the dev server at \`/games/live/Battle Drones/static/iframeTest.html\`.
`
);

console.log(`Wrote ${dest} from ${commit}${dirty ? " (uncommitted changes)" : ""}`);
